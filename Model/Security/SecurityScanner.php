<?php

declare(strict_types=1);

namespace DockCodes\DockRay\Model\Security;

/**
 * Filesystem side of the security report: group digests over a per-file hash
 * cache, sensitive single files and suspicious files in upload directories.
 *
 * Returns hashes, sizes, relative paths and indicator names only - never file
 * contents or absolute paths. Every walk is bounded by a deadline and a file
 * budget; a walk that hits either marks the scan truncated instead of passing
 * off a partial result as complete.
 *
 * Platform-neutral on purpose: the Laravel bridge
 * (`Dock\Ray\Laravel\Security\SecurityScanner`) and the PrestaShop module
 * (`Dock\Ray\PrestaShop\SecurityScanner`) ship the same class, and they must
 * stay in step so a digest means the same thing on every platform. This copy
 * differs in three places, all forced by what a stock Magento keeps in
 * `pub/media` and all backwards compatible:
 *
 * - `PHP_HANDLER` looks at the handler or type a directive sets, not at the
 *   whole line: Magento's own `pub/media/.htaccess` says
 *   `AddHandler cgi-script .php …` (with `Options -ExecCGI`) to stop PHP
 *   there, and the line-wide pattern took that for the opposite;
 * - `uploads()` takes path prefixes to skip (the resized product image cache,
 *   regenerated by Magento and most of `pub/media` on a large catalogue);
 * - `uploads()` takes hidden directories the platform creates itself
 *   (`.thumbs`, `.renditions`), which are not reported but still scanned.
 *
 * A fourth difference is a fix the other copies need as well: `\` becomes
 * `/` only on Windows, where it is the separator. On Linux it is an ordinary
 * file name character, so a planted `pub/media/..\x.php` used to be sent as
 * `pub/media/../x.php` - a path DockRay rejects, together with the whole
 * report. Now `path()` turns it into `pub/media/..?x.php` and the file is
 * reported like any other.
 */
final class SecurityScanner
{
    /** Extensions that make up a group digest (contract: `groups`). */
    private const GROUP_EXTENSIONS = ['php', 'phtml', 'phar', 'inc', 'js', 'htaccess'];

    /** Extensions PHP may execute when they sit in an upload directory. */
    private const PHP_EXTENSIONS = ['php', 'phtml', 'phar', 'pht', 'phps', 'php3', 'php4', 'php5', 'php6', 'php7', 'php8'];

    private const VCS_DIRECTORIES = ['.git', '.svn', '.hg'];

    /** Webshells are small; reading further only costs time on vendored libraries. */
    private const MAX_INDICATOR_BYTES = 524288;

    /** An inert `index.php` (licence header, a few `header()` calls) is well below this. */
    private const MAX_INERT_INDEX_BYTES = 8192;

    private const MEDIA_HEAD_BYTES = 1024;

    /** Media larger than this is not sniffed; a webshell disguised as an image is small. */
    private const SNIFF_MAX_SIZE = 5242880;

    private const MAX_RULES_BYTES = 65536;

    private const MAX_PATH = 512;

    private const MAX_INDICATORS = 10;

    /** How often unchanged uploads are read again, not only the ones that changed. */
    private const FULL_SCAN_INTERVAL = 604800;

    /** ctime granularity and clock skew between PHP and the filesystem. */
    private const CTIME_MARGIN = 120;

    /**
     * An `.htaccess` or `.user.ini` that makes the server run PHP in an upload
     * directory (contract: `php_handler`). The handler or MIME type itself must
     * name PHP: `AddType application/x-httpd-php .jpg` and `SetHandler
     * "proxy:unix:/run/php/fpm.sock|fcgi://localhost"` match, the defensive
     * `AddHandler cgi-script .php` and `AddType text/plain .php` do not.
     */
    private const PHP_HANDLER = '/(?:AddHandler|SetHandler|AddType|ForceType)[ \t]+["\']?[^\s"\']*(?:php|x-httpd)|auto_(?:prepend|append)_file|php_(?:flag|value)\s+engine\s+(?:on|1)\b/i';

    /**
     * Backdoor indicators by contract name. Only the names leave the server,
     * never the matched text. `(?<![\w$>:])` keeps method calls such as
     * `$process->system()` out of the function-call patterns.
     */
    private const INDICATORS = [
        'eval' => '/(?<![\w$>:])eval\s*\(/i',
        'assert' => '/(?<![\w$>:])assert\s*\(\s*(?:@\s*)?(?:\$|base64_decode|str_rot13|gz(?:inflate|uncompress|decode)|stripslashes)/i',
        'create_function' => '/(?<![\w$>:])create_function\s*\(/i',
        'base64_eval' => '/(?<![\w$>:])(?:eval|assert)\s*\([^;]{0,200}?\bbase64_decode\s*\(/is',
        'gzinflate' => '/(?<![\w$>:])gz(?:inflate|uncompress)\s*\(/i',
        'str_rot13' => '/(?<![\w$>:])str_rot13\s*\(/i',
        'hex2bin_eval' => '/(?<![\w$>:])(?:eval|assert)\s*\([^;]{0,200}?\bhex2bin\s*\(/is',
        'remote_fetch' => '/(?<![\w$>:])(?:file_get_contents|fopen|readfile|file|copy|fsockopen|pfsockopen|stream_socket_client)\s*\(\s*[\'"](?:https?|ftp):\/\/|(?<![\w$>:])curl_exec\s*\(/i',
        'remote_include' => '/\b(?:include|require)(?:_once)?\b\s*\(?\s*(?:[\'"](?:https?|ftp|data|php):\/\/|\$_(?:GET|POST|REQUEST|COOKIE|SERVER|FILES)\b)/i',
        'zip_include' => '/\b(?:include|require)(?:_once)?\b\s*\(?\s*[\'"](?:zip|compress\.zlib|compress\.bzip2|rar):\/\//i',
        'phar_include' => '/\b(?:include|require)(?:_once)?\b\s*\(?\s*[\'"]phar:\/\//i',
        'php_input' => '/php:\/\/input/i',
        'request_exec' => '/(?<![\w$>:])(?:eval|assert|system|exec|shell_exec|passthru|popen|proc_open|pcntl_exec|call_user_func(?:_array)?|create_function)\s*\(\s*(?:@\s*)?(?:(?:stripslashes|base64_decode|trim|urldecode|rawurldecode|str_rot13)\s*\(\s*)*\$_(?:GET|POST|REQUEST|COOKIE|SERVER|FILES)\b|\$_(?:GET|POST|REQUEST|COOKIE)\s*\[[^\]]{1,64}\]\s*\(/i',
        'shell_exec' => '/(?<![\w$>:])(?:shell_exec|system|passthru|exec|popen|proc_open|pcntl_exec)\s*\(/i',
        'preg_replace_e' => '/(?<![\w$>:])preg_replace\s*\(\s*([\'"])([^\w\s\\\\])(?:(?!\2).){0,300}\2[a-zA-Z]*e[a-zA-Z]*\1/is',
        'chmod_444' => '/(?<![\w$>:])chmod\s*\([^;]{0,200}?\b0?444\b/is',
        'self_delete' => '/(?<![\w$>:])unlink\s*\(\s*(?:__FILE__|\$_SERVER\s*\[\s*[\'"](?:SCRIPT_FILENAME|PHP_SELF)[\'"]\s*\])/i',
        'obfuscated_call' => '/(?<![\w$>:])call_user_func(?:_array)?\s*\(\s*pack\s*\(\s*[\'"]H\*[\'"]/i',
        'chr_obfuscation' => '/(?<![\w$>:])chr\s*\(\s*\d{1,3}\s*\)\s*\.\s*chr\s*\(\s*\d{1,3}\s*\)\s*\.\s*chr\s*\(/i',
    ];

    private string $root;

    /** @var array<string, array{0: int, 1: int, 2: int, 3: string}> relative path => [size, mtime, ctime, sha256] */
    private array $cache;

    /** @var array<string, array{0: int, 1: int, 2: int, 3: string}> */
    private array $seen = [];

    private float $deadline;

    private int $maxFiles;

    private int $files = 0;

    private bool $truncated = false;

    /**
     * @param array<string, mixed> $cache the hash cache returned by `cache()` on the previous run
     */
    public function __construct(string $root, array $cache, float $deadline, int $maxFiles)
    {
        $this->root = rtrim(self::separators($root), '/');
        $this->cache = $cache;
        $this->deadline = $deadline;
        $this->maxFiles = $maxFiles;
    }

    /** Files looked at during this scan, for `scan.files`. */
    public function files(): int
    {
        return $this->files;
    }

    public function truncated(): bool
    {
        return $this->truncated;
    }

    public function markTruncated(): void
    {
        $this->truncated = true;
    }

    /**
     * The hash cache to keep for the next run. A complete scan keeps only the
     * files it saw, so deleted files do not pile up; a truncated one keeps the
     * old entries too, or the next run would rehash what this one never reached.
     *
     * @return array<string, array{0: int, 1: int, 2: int, 3: string}>
     */
    public function cache(): array
    {
        return $this->truncated ? $this->seen + $this->cache : $this->seen;
    }

    /**
     * One `groups` entry, or null when the scan ran out of time or files
     * before every file of the group was hashed: a partial digest would look
     * exactly like a modified group.
     *
     * @param list<string> $directories relative to the application root
     * @param list<string> $exclude     relative path prefixes left out of the digest (generated files)
     * @param string       $base        prefix stripped from paths, so they are relative to the group root
     *
     * @return array{type: string, slug: string, version: string|null, files: int, digest: string}|null
     */
    public function group(string $type, string $slug, ?string $version, array $directories, string $base = '', array $exclude = []): ?array
    {
        if ($this->truncated) {
            return null;
        }

        $hashes = [];

        foreach ($directories as $directory) {
            foreach ($this->walk($directory, $exclude, false) as $entry) {
                [$relative, $absolute, $stat] = $entry;

                if (! in_array(self::extension($relative), self::GROUP_EXTENSIONS, true)) {
                    continue;
                }

                $hash = $this->hash($relative, $absolute, $stat);

                if ($hash !== null) {
                    $hashes[$base !== '' && strncmp($relative, $base, strlen($base)) === 0 ? substr($relative, strlen($base)) : $relative] = $hash;
                }
            }

            if ($this->truncated) {
                return null;
            }
        }

        uksort($hashes, 'strcmp');
        $context = hash_init('sha256');

        foreach ($hashes as $path => $hash) {
            hash_update($context, $path."\0".$hash."\n");
        }

        return [
            'type' => $type,
            'slug' => $slug,
            'version' => $version,
            'files' => count($hashes),
            'digest' => hash_final($context),
        ];
    }

    /**
     * One `files` entry for a sensitive single file, or null when it does not
     * exist. Hashing `.env` tells DockRay when it changed and nothing else.
     *
     * @return array{path: string, role: string, sha256: string, size: int}|null
     */
    public function file(string $relative, string $role): ?array
    {
        $absolute = $this->root.'/'.$relative;
        $stat = is_file($absolute) ? @stat($absolute) : false;

        if ($stat === false) {
            return null;
        }

        $this->files++;
        $hash = $this->hash($relative, $absolute, $stat);

        $path = self::path($relative);

        return $hash === null || $path === null ? null : ['path' => $path, 'role' => $role, 'sha256' => $hash, 'size' => (int) $stat['size']];
    }

    /**
     * PHP files directly in a web-reachable directory: a file the platform
     * does not ship is `unknown_root_php`, a shipped one with backdoor
     * indicators is `suspicious_code`.
     *
     * @param list<string> $shipped file names the platform puts there
     *
     * @return list<array<string, mixed>>
     */
    public function rootPhp(string $directory, array $shipped): array
    {
        $absoluteDirectory = $directory === '' ? $this->root : $this->root.'/'.$directory;
        $names = is_dir($absoluteDirectory) ? @scandir($absoluteDirectory) : false;
        $entries = [];

        foreach (is_array($names) ? $names : [] as $name) {
            $absolute = $absoluteDirectory.'/'.$name;

            if (! in_array(self::extension($name), self::PHP_EXTENSIONS, true) || ! is_file($absolute)) {
                continue;
            }

            $this->files++;
            $relative = $directory === '' ? $name : $directory.'/'.$name;
            $stat = @stat($absolute);
            $indicators = $this->indicators($absolute);
            $known = in_array($name, $shipped, true);

            if ($known && $indicators === []) {
                continue;
            }

            $entry = $this->suspicious($relative, $known ? 'suspicious_code' : 'unknown_root_php', $stat, $indicators);

            if ($entry !== null) {
                $entries[] = $entry;
            }
        }

        return $entries;
    }

    /**
     * Upload directories: PHP that does not belong there, PHP disguised as
     * media, server rules that make PHP run there, hidden directories.
     *
     * Every run walks all names (cheap) and judges PHP files by extension and
     * `.htaccess`/`.user.ini` by their rules. File contents are read only when
     * `ctime` is at or after the start of the previous run, plus a weekly
     * full pass under `$sniffBudget` seconds per run that continues from a
     * cursor. Earlier findings are carried over for files whose `ctime` did
     * not change, so every report is the complete state. A walk stopped by
     * the entry limit or the deadline marks the scan truncated and does not
     * advance the "previous run" time.
     *
     * @param list<string>         $directories   relative to the application root
     * @param array<string, mixed> $state         returned by the previous call
     * @param list<string>         $exclude       relative path prefixes not walked at all (regenerated caches)
     * @param list<string>         $allowedHidden relative paths of hidden directories the platform creates;
     *                                            not reported, their files are still judged
     *
     * @return array{entries: list<array<string, mixed>>, state: array<string, mixed>}
     */
    public function uploads(array $directories, array $state, int $now, float $sniffBudget, int $maxEntries, array $exclude = [], array $allowedHidden = []): array
    {
        $since = (int) ($state['since'] ?? 0);
        $cursor = (int) ($state['cursor'] ?? 0);
        $full = $since <= 0 || $cursor > 0 || $now - (int) ($state['full_at'] ?? 0) >= self::FULL_SCAN_INTERVAL;
        $fullStarted = $cursor > 0 ? (int) ($state['full_started'] ?? $now) : $now;
        $known = is_array($state['known'] ?? null) ? $state['known'] : [];
        $changedAfter = $since <= 0 ? PHP_INT_MIN : $since - self::CTIME_MARGIN;
        $sniffUntil = microtime(true) + $sniffBudget;
        $entries = [];
        $carried = [];
        $visited = 0;
        $position = 0;
        $stoppedAt = null;
        $stopped = false;

        foreach ($directories as $directory) {
            foreach ($this->walk($directory, $exclude, true) as $entry) {
                [$relative, $absolute, $stat] = $entry;

                if (++$visited > $maxEntries) {
                    $stopped = true;

                    break 2;
                }

                if ($stat === null) {
                    $found = in_array($relative, $allowedHidden, true) ? null : $this->hiddenDirectory($relative);

                    if ($found !== null) {
                        $entries[] = $found;
                    }

                    continue;
                }

                $name = strtolower(basename($relative));
                $php = in_array(self::extension($name), self::PHP_EXTENSIONS, true);

                // Judged on every run, without a cache: a PHP file is suspicious
                // by its name, server rules are few and small.
                if ($php && ! ($name === 'index.php' && (int) $stat['size'] <= self::MAX_INERT_INDEX_BYTES)) {
                    $found = $this->suspicious($relative, 'php_in_uploads', $stat, $this->indicators($absolute));

                    if ($found !== null) {
                        $entries[] = $found;
                    }

                    continue;
                }

                if ($name === '.htaccess' || $name === '.user.ini') {
                    $rules = @file_get_contents($absolute, false, null, 0, self::MAX_RULES_BYTES);

                    $found = is_string($rules) && preg_match(self::PHP_HANDLER, $rules) === 1
                        ? $this->suspicious($relative, 'suspicious_code', $stat, ['php_handler'])
                        : null;

                    if ($found !== null) {
                        $entries[] = $found;
                    }

                    continue;
                }

                // Everything else needs its contents read: media, and `index.php`
                // that may be an inert directory guard.
                $index = $position++;
                $ctime = (int) $stat['ctime'];
                $previous = $known[$relative] ?? null;

                if (is_array($previous) && (int) ($previous['ctime'] ?? -1) === $ctime && is_array($previous['entry'] ?? null)) {
                    $entries[] = $previous['entry'];
                    $carried[$relative] = $previous;

                    continue;
                }

                $resniff = $full && $stoppedAt === null && $index >= $cursor;

                if ($resniff && microtime(true) > $sniffUntil) {
                    $stoppedAt = $index;
                    $resniff = false;
                }

                if (! $resniff && $ctime < $changedAfter) {
                    continue;
                }

                $found = $this->sniff($relative, $absolute, $stat, $php);

                if ($found !== null) {
                    $entries[] = $found;
                    $carried[$relative] = ['ctime' => $ctime, 'entry' => $found];
                }
            }

            if ($this->truncated) {
                $stopped = true;

                break;
            }
        }

        if ($stopped) {
            // Findings are not closed for files the walk never reached, and the
            // next run looks again at everything that changed since the last
            // complete one.
            $this->truncated = true;

            return ['entries' => $entries, 'state' => $state];
        }

        return ['entries' => $entries, 'state' => [
            'since' => $now,
            'full_at' => $full && $stoppedAt === null ? $fullStarted : (int) ($state['full_at'] ?? 0),
            'full_started' => $full && $stoppedAt !== null ? $fullStarted : 0,
            'cursor' => $full && $stoppedAt !== null ? $stoppedAt : 0,
            'known' => $carried,
        ]];
    }

    /**
     * Indicator names found in a PHP file, at most ten.
     *
     * @return list<string>
     */
    public function indicators(string $absolute): array
    {
        $code = @file_get_contents($absolute, false, null, 0, self::MAX_INDICATOR_BYTES);

        return is_string($code) ? self::indicatorsIn($code) : [];
    }

    /** @return list<string> */
    public static function indicatorsIn(string $code): array
    {
        $found = [];

        foreach (self::INDICATORS as $name => $pattern) {
            if (preg_match($pattern, $code) === 1) {
                $found[] = $name;

                if (count($found) >= self::MAX_INDICATORS) {
                    break;
                }
            }
        }

        return $found;
    }

    /**
     * An `index.php` that cannot run anything: empty, comments only ("Silence
     * is golden") or the directory guard PrestaShop and many modules ship -
     * a licence header, `header()` calls with literal strings and `exit`.
     *
     * Comments are consumed from the start of the file only, the way PHP
     * reads them; whatever follows must match the allowlist in full, so code
     * hidden behind a comment-looking string does not pass.
     */
    public static function isInertIndex(string $code): bool
    {
        if (strncmp($code, "\xEF\xBB\xBF", 3) === 0) {
            $code = substr($code, 3);
        }

        if (trim($code) === '') {
            return true;
        }

        if (preg_match('/^\s*<\?php(?=\s|$)/i', $code, $open) !== 1) {
            return false;
        }

        $rest = substr($code, strlen($open[0]));

        while (true) {
            $rest = ltrim($rest);

            if (strncmp($rest, '/*', 2) === 0) {
                $end = strpos($rest, '*/', 2);

                if ($end === false) {
                    return false;
                }

                $rest = substr($rest, $end + 2);

                continue;
            }

            if (preg_match('/^(?:\/\/|#(?!\[))([^\r\n]*)/', $rest, $line) === 1) {
                // A closing tag ends PHP mode even inside a line comment; what follows would be output or more code.
                if (strpos($line[1], '?>') !== false) {
                    return false;
                }

                $rest = substr($rest, strlen($line[0]));

                continue;
            }

            break;
        }

        // Literal strings only: no escapes, and no `$` that could interpolate.
        $string = '(?:\'[^\'\\\\]*\'|"[^"\\\\$]*")';
        $header = 'header\s*\(\s*'.$string.'(?:\s*\.\s*gmdate\s*\(\s*'.$string.'\s*\))?(?:\s*\.\s*'.$string.')?\s*(?:,\s*(?:true|false))?\s*\)\s*;';
        $exit = '(?:exit|die)\s*(?:\(\s*\d*\s*\))?\s*;';

        return preg_match('/^(?:\s*(?:'.$header.'|'.$exit.'))*\s*(?:\?>\s*)?$/i', $rest) === 1;
    }

    /**
     * Relative path as the contract wants it: `/` separators, at most 512
     * bytes, nothing DockRay would refuse - one refused path fails the whole
     * report. Backslashes and control characters (a Linux file name may hold
     * both) become `?`, and so does the colon of a leading `c:` that would
     * read as a drive letter, so the file is still reported. Null only when
     * cutting a long path left a `..` segment; the walk itself never
     * produces `..` or a leading `/`.
     */
    public static function path(string $relative): ?string
    {
        $path = preg_replace('/[\x00-\x1F\x7F\\\\]/', '?', $relative) ?? '';

        if (strlen($path) > self::MAX_PATH) {
            $path = function_exists('mb_strcut') ? mb_strcut($path, 0, self::MAX_PATH, 'UTF-8') : substr($path, 0, self::MAX_PATH);
        }

        if (preg_match('/^[A-Za-z]:/', $path) === 1) {
            $path[1] = '?';
        }

        return self::isRelativePath($path) ? $path : null;
    }

    /** The rule DockRay applies to every reported path (`SecurityReportIngest::isRelativePath`). */
    public static function isRelativePath(string $path): bool
    {
        return $path !== ''
            && $path[0] !== '/'
            && strpos($path, '\\') === false
            && preg_match('/[\x00-\x1F\x7F]/', $path) !== 1
            && ! in_array('..', explode('/', $path), true)
            && preg_match('/^[A-Za-z]:/', $path) !== 1;
    }

    public static function extension(string $path): string
    {
        return strtolower(pathinfo($path, PATHINFO_EXTENSION));
    }

    /** @return array<string, mixed>|null */
    private function hiddenDirectory(string $relative): ?array
    {
        $name = basename($relative);

        if ($name === '' || $name[0] !== '.' || $name === '.well-known') {
            return null;
        }

        $path = self::path($relative);

        return $path === null ? null : ['path' => $path, 'kind' => 'hidden_directory'];
    }

    /**
     * Reads one upload: an `index.php` that is not an inert guard is
     * `php_in_uploads`, any other file starting with `<?php` is `php_in_media`.
     *
     * @param array<string|int, int> $stat
     *
     * @return array<string, mixed>|null
     */
    private function sniff(string $relative, string $absolute, array $stat, bool $php): ?array
    {
        if ($php) {
            $code = @file_get_contents($absolute);

            return is_string($code) && self::isInertIndex($code)
                ? null
                : $this->suspicious($relative, 'php_in_uploads', $stat, $this->indicators($absolute));
        }

        if ((int) $stat['size'] > self::SNIFF_MAX_SIZE) {
            return null;
        }

        $head = @file_get_contents($absolute, false, null, 0, self::MEDIA_HEAD_BYTES);

        return is_string($head) && stripos($head, '<?php') !== false
            ? $this->suspicious($relative, 'php_in_media', $stat, $this->indicators($absolute))
            : null;
    }

    /**
     * @param array<string|int, int>|false|null $stat
     * @param list<string>                      $indicators
     *
     * @return array<string, mixed>|null
     */
    private function suspicious(string $relative, string $kind, $stat, array $indicators): ?array
    {
        $path = self::path($relative);

        if ($path === null) {
            return null;
        }

        $entry = ['path' => $path, 'kind' => $kind];

        if (is_array($stat)) {
            $entry['size'] = (int) $stat['size'];
            $entry['mtime'] = max(0, (int) $stat['mtime']);
        }

        if ($indicators !== []) {
            $entry['indicators'] = $indicators;
        }

        return $entry;
    }

    /**
     * sha256 of a file through the cache. `ctime` is part of the key because
     * PHP cannot set it: touching a modified file back to its old mtime does
     * not hide the change.
     *
     * @param array<string|int, int> $stat
     */
    private function hash(string $relative, string $absolute, array $stat): ?string
    {
        $key = [(int) $stat['size'], (int) $stat['mtime'], (int) $stat['ctime']];
        $cached = $this->cache[$relative] ?? null;

        if (is_array($cached) && count($cached) === 4 && array_slice($cached, 0, 3) === $key && is_string($cached[3])) {
            $this->seen[$relative] = $cached;

            return $cached[3];
        }

        $hash = @hash_file('sha256', $absolute);

        if (! is_string($hash)) {
            return null;
        }

        $this->seen[$relative] = [$key[0], $key[1], $key[2], $hash];

        return $hash;
    }

    /**
     * Files (and, with `$directories`, directories) below a relative
     * directory. Symlinked directories are not followed - they can point
     * anywhere, including back up the tree. Stops, and marks the scan
     * truncated, when the deadline or the file budget runs out.
     *
     * @param list<string> $exclude relative path prefixes to skip
     *
     * @return \Generator<int, array{0: string, 1: string, 2: array<string|int, int>|null}>
     */
    private function walk(string $directory, array $exclude, bool $directories): \Generator
    {
        $start = $this->root.'/'.trim($directory, '/');

        if (! is_dir($start)) {
            return;
        }

        try {
            $iterator = new \RecursiveIteratorIterator(
                new \RecursiveCallbackFilterIterator(
                    new \RecursiveDirectoryIterator($start, \FilesystemIterator::SKIP_DOTS | \FilesystemIterator::CURRENT_AS_FILEINFO),
                    function (\SplFileInfo $file) use ($exclude): bool {
                        if (! $file->isDir() || $file->isLink()) {
                            return true;
                        }

                        if (in_array($file->getFilename(), self::VCS_DIRECTORIES, true)) {
                            return false;
                        }

                        $relative = $this->relative($file->getPathname()).'/';

                        foreach ($exclude as $prefix) {
                            if (strncmp($relative, $prefix, strlen($prefix)) === 0) {
                                return false;
                            }
                        }

                        return true;
                    }
                ),
                $directories ? \RecursiveIteratorIterator::SELF_FIRST : \RecursiveIteratorIterator::LEAVES_ONLY,
                \RecursiveIteratorIterator::CATCH_GET_CHILD
            );

            foreach ($iterator as $file) {
                if (microtime(true) >= $this->deadline || $this->files >= $this->maxFiles) {
                    $this->truncated = true;

                    return;
                }

                $relative = $this->relative($file->getPathname());

                if ($file->isDir()) {
                    if ($directories) {
                        yield [$relative, $file->getPathname(), null];
                    }

                    continue;
                }

                if (! $file->isFile() || $this->excluded($relative, $exclude)) {
                    continue;
                }

                $stat = @stat($file->getPathname());

                if ($stat === false) {
                    continue;
                }

                $this->files++;

                yield [$relative, $file->getPathname(), $stat];
            }
        } catch (\UnexpectedValueException $exception) {
            // An unreadable directory is skipped, not fatal.
        }
    }

    /** @param list<string> $exclude */
    private function excluded(string $relative, array $exclude): bool
    {
        foreach ($exclude as $prefix) {
            if ($relative === rtrim($prefix, '/') || strncmp($relative, $prefix, strlen($prefix)) === 0) {
                return true;
            }
        }

        return false;
    }

    private function relative(string $absolute): string
    {
        return ltrim(substr(self::separators($absolute), strlen($this->root)), '/');
    }

    /** `\` is a separator on Windows only; elsewhere it belongs to the file name and `path()` deals with it. */
    public static function separators(string $path): string
    {
        return DIRECTORY_SEPARATOR === '\\' ? str_replace('\\', '/', $path) : $path;
    }
}
